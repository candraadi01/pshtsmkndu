-- Migration 0003: Admin RBAC, Analytics, and Write Policies for CMS
-- Allows authenticated admins and super_admins to perform CRUD on all tables.

begin;

-- 1. Site Visits (Analytics & Traffic Tracking)
create table if not exists public.site_visits (
  id bigint generated by default as identity primary key,
  path text not null,
  ip_hash text,
  user_agent text,
  created_at timestamptz not null default now()
);

create index if not exists site_visits_created_at_idx on public.site_visits (created_at desc);
create index if not exists site_visits_path_idx on public.site_visits (path);

alter table public.site_visits enable row level security;
revoke all on table public.site_visits from anon, authenticated;
grant insert on table public.site_visits to anon, authenticated;
grant select on table public.site_visits to authenticated;

create policy site_visits_public_insert on public.site_visits for insert to anon, authenticated with check (true);

-- 2. Helper functions to check admin roles
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid()
      and role in ('admin', 'super_admin')
  );
$$;

create or replace function public.is_super_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid()
      and role = 'super_admin'
  );
$$;

grant execute on function public.is_admin() to authenticated;
grant execute on function public.is_super_admin() to authenticated;

-- 3. Trigger to automatically create profile on new auth.users signup
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  has_super boolean;
begin
  select exists (select 1 from public.profiles where role = 'super_admin') into has_super;

  insert into public.profiles (id, display_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    case when not has_super then 'super_admin' else coalesce(new.raw_user_meta_data->>'role', 'admin') end
  )
  on conflict (id) do update
  set role = case when not has_super then 'super_admin' else profiles.role end;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 4. Grant full CRUD permissions to authenticated role for all content tables
grant all on table public.artikel to authenticated;
grant all on table public.pengumuman to authenticated;
grant all on table public.ekstrakurikuler to authenticated;
grant all on table public.galleries to authenticated;
grant all on table public.images to authenticated;
grant all on table public.people to authenticated;
grant all on table public.page_settings to authenticated;
grant all on table public.tipe_dokumen to authenticated;
grant all on table public.dokumen to authenticated;
grant all on table public.profiles to authenticated;

-- Grant sequence usages for tables with identity columns
grant usage, select on all sequences in schema public to authenticated;

-- 5. RLS Write Policies (Admin & Super Admin)

