create policy profiles_read on public.profiles for select to authenticated using (true);
create policy profiles_update_own on public.profiles for update to authenticated using (id = auth.uid() or public.is_super_admin());
create policy profiles_superadmin_all on public.profiles for all to authenticated using (public.is_super_admin());

-- Site visits read policy
create policy site_visits_admin_read on public.site_visits for select to authenticated using (public.is_admin());

